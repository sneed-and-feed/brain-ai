            "        opt_pure.step()\n",
            "        \n",
            "    with torch.no_grad():\n",
            "        rh_in_t = arc_embedder(test_in)\n",
            "        out_pure = brain(lh_latents=torch.zeros(1, 32, brain.d_lh, device=device), rh_inputs=rh_in_t)\n",
