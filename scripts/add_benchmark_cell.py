            "        if match:\n",
            "            p_arr = np.array(json.loads(match.group(0)))\n",
            "            if p_arr.shape == gt_grid.shape:\n",
            "                raw_llama_acc = (p_arr == gt_grid).mean() * 100.0\n",
            "    except Exception:\n",
            "        raw_llama_acc = 0.0\n",
            "    raw_llama_time = (time.time() - t0) * 1000\n",
